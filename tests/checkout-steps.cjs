'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const html=fs.readFileSync('index.html','utf8');
const cart=fs.readFileSync('cart.mjs','utf8');
assert.equal((html.match(/data-checkout-step="[123]"/g)||[]).length,3);
assert.equal((html.match(/data-progress-step="[123]"/g)||[]).length,3);
assert.equal((html.match(/data-next-step="[23]"/g)||[]).length,2);
assert.ok(html.indexOf('data-checkout-step="1"')<html.indexOf('data-checkout-step="2"'));
assert.ok(html.indexOf('data-checkout-step="2"')<html.indexOf('data-checkout-step="3"'));
assert.match(html,/Não há cobrança online aqui/);
assert.match(html,/Abrir pedido no WhatsApp/);
assert.match(html,/aria-current="step"/);
assert.match(cart,/checkoutStepValid\(step\)/);
assert.match(cart,/updateCheckoutProgress\(target\)/);
assert.match(cart,/checkoutForm\.addEventListener\('focusin'/);
assert.match(html,/name="consent"[^>]*required/);
assert.match(html,/id="captureLocation"/);
assert.match(html,/id="sendOrder" disabled/);
assert.match(html,/id="whatsappOrderLink"/);
console.log('PASS: fluxo WhatsApp mantém etapas guiadas, consentimento e link de contingência.');
