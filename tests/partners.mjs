import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';
import { approvedPartners, renderPartners } from '../partners.mjs';
const doc = new JSDOM('<section hidden><div data-partners-list></div></section>').window.document;
const root = doc.querySelector('section');
const valid = {name:'Parceiro teste',description:'Comércio local',url:'https://example.invalid',active:true};
assert.deepEqual(approvedPartners([{...valid,url:'javascript:alert(1)'},{...valid,url:'http://example.invalid'},{...valid,active:false}]),[]);
assert.equal(approvedPartners(Array(6).fill(valid)).length,3);
assert.equal(approvedPartners([{...valid,logo:'https://example.invalid/pixel.png'}])[0].logo,null);
renderPartners(root,[]);
assert.equal(root.hidden,true);
renderPartners(root,[{...valid,name:'<img src=x onerror=alert(1)>'}]);
assert.equal(root.hidden,false);
assert.equal(root.querySelectorAll('img').length,0);
assert.equal(root.querySelector('strong').textContent,'<img src=x onerror=alert(1)>');
assert.equal(root.querySelector('a').rel,'sponsored noopener noreferrer');
renderPartners(root);
assert.equal(root.querySelector('a').href,'https://xtltech.com.br/');
renderPartners(root,[]);
assert.equal(root.hidden,true);
console.log('PASS partners: small inventory, safe text, HTTPS links, empty-state hiding and no tracking.');
