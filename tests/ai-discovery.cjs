'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const data=p=>JSON.parse(read(p));
const html=read('index.html');
const profile=data('ai/business.json');
const catalog=data('cardapio.json');
const summary=data('ai/catalog-summary.json');
const title=html.match(/<title>([^<]+)<\/title>/)?.[1];
assert.match(title,/Disk Panquecão/);
const header=html.split(/<header(?:\s[^>]*)?>/i)[1]?.split(/<\/header>/i)[0];
assert.ok(header,'header missing');
assert.doesNotMatch(header,/9738-3849|Praça do Trabalhador/);
const footer=html.split(/<footer(?:\s[^>]*)?>/i)[1]?.split(/<\/footer>/i)[0];
assert.match(footer,/9738-3849/);
assert.match(footer,/Praça do Trabalhador/);
assert.doesNotMatch(html,/O cardápio completo também está logo abaixo/);
assert.match(html,/<link rel="canonical" href="https:\/\/opanquecao\.vercel\.app\/"/);
assert.match(html,/href="\/llms\.txt"/);
assert.match(html,/href="\/ai\/business\.json"/);
const ldText=html.match(/<script type="application\/ld\+json">\s*([\s\S]*?)<\/script>/)?.[1];
assert.ok(ldText,'Restaurant JSON-LD must exist');
const ld=JSON.parse(ldText);
assert.equal(ld['@type'],'Restaurant');
assert.equal(ld.telephone,profile.contacts.phone_e164);
assert.equal(ld.name,profile.business_name);
assert.equal(ld.hasMenu,profile.menu.page_url);
assert.deepEqual(ld.areaServed.map(x=>x.name),profile.delivery.cities.map(x=>x.city));
assert.equal(profile.hours.verified_by_owner,false);
assert.ok(!('openingHoursSpecification' in ld),'Unverified hours must not be given as official structured data');
assert.equal(profile.orders.online_payment_charged,false);
assert.equal(profile.orders.automatic_acceptance,false);
assert.equal(catalog.categorias.reduce((sum,c)=>sum+c.itens.length,0),82);
assert.equal(catalog.categorias.length,12);
assert.deepEqual(summary.categories.map(c=>c.slug),catalog.categorias.map(c=>c.id));
assert.deepEqual(summary.categories.map(c=>c.products),catalog.categorias.map(c=>c.itens.length));
assert.equal(summary.total_products,82);
assert.equal(profile.menu.product_count,82);
assert.equal(profile.menu.category_count,12);
assert.equal(new Set(catalog.observacoes).size,catalog.observacoes.length);
assert.equal(catalog.observacoes.length,4);
assert.ok(!catalog.observacoes.some(s=>/toda Nova Hartz|taxa de entrega sob consulta por bairro|45 a 55/i.test(s)));
for(const p of ['llms.txt','llms-full.txt','ai/agents.md','ai/faq.md','robots.txt','sitemap.xml'])assert.ok(read(p).length>80,p+' missing or empty');
assert.match(read('robots.txt'),/Sitemap: https:\/\/opanquecao\.vercel\.app\/sitemap\.xml/);
assert.match(read('sitemap.xml'),/https:\/\/opanquecao\.vercel\.app\//);
assert.match(read('llms.txt'),/não confirmados|não confirmados|NÃO confirmados/i);
const forbidden=/TELEGRAM_BOT_TOKEN|TURNSTILE_SECRET_KEY|SUPABASE_SECRET_KEY|service_role|chat_id/i;
for(const p of ['llms.txt','llms-full.txt','ai/business.json','ai/agents.md','ai/faq.md','ai/catalog-summary.json'])assert.doesNotMatch(read(p),forbidden,p+' must not expose internal implementation/secrets');
console.log('PASS: AI discovery, SEO, public info consistency, non-duplication and 82 preserved products.');
