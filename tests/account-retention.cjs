'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
(async()=>{
 const h=fs.readFileSync('index.html','utf8'),cart=fs.readFileSync('cart.mjs','utf8'),account=fs.readFileSync('minha-conta.html','utf8');
 for(const id of ['customerAccountNav','checkoutAccountLogout','accountJoinLink','savedAddressSelect'])assert.match(h,new RegExp('id="'+id+'"'));
 assert.match(cart,/if\(accountNav\)void detectAccount\(\)/);
 assert.match(cart,/void detectAccount\(\{checkout:true\}\)/);
 assert.match(cart,/accountRequest\('logout',\{\}\)/);
 assert.match(cart,/epoch!==accountEpoch/);
 assert.match(h,/quando o programa for liberado/);
 assert.match(account,/O acúmulo começa quando o programa estiver ativo/);
 const storage=new Map();
 global.document={body:{dataset:{premiumPreview:'true'}}};
 global.sessionStorage={getItem:k=>storage.get(k)||null,setItem:(k,v)=>storage.set(k,v),removeItem:k=>storage.delete(k)};
 global.fetch=()=>{throw Error('demo must never call network');};
 const {accountRequest}=await import('../customer-account-client.mjs');
 await assert.rejects(()=>accountRequest('state'),e=>e.status===401);
 await assert.rejects(()=>accountRequest('otp_verify',{email:'cliente@example.test',otp:'000000'}),e=>e.status===401);
 await accountRequest('otp_verify',{email:'cliente@example.test',otp:'123456'});
 assert.equal((await accountRequest('state')).profile.name,'Cliente de demonstração');
 assert.equal((await accountRequest('addresses')).addresses.length,2);
 await accountRequest('profile_save',{name:'Cliente Fictício',phone:'51999999999'});
 assert.equal((await accountRequest('state')).profile.name,'Cliente Fictício');
 await accountRequest('logout',{});
 await assert.rejects(()=>accountRequest('state'),e=>e.status===401);
 assert.equal(storage.size,0);
 console.log('PASS: account auto-detection hooks, clear loyalty status, demo login/logout and no external traffic.');
})().catch(e=>{console.error(e);process.exitCode=1});
