'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {JSDOM}=require('jsdom');
const pixel=fs.readFileSync('meta-pixel.js','utf8');
const category=fs.readFileSync('categorias/acai.html','utf8');
const w=new JSDOM(category,{url:'https://opanquecao.vercel.app/categorias/acai.html',
    runScripts:'outside-only'}).window;
const d=w.document;
w.eval(pixel);
d.dispatchEvent(new w.Event('DOMContentLoaded'));
const notice=d.getElementById('analyticsNotice');
assert.ok(notice,'Categoria precisa oferecer escolha de privacidade');
assert.equal(notice.hidden,false,'Aviso necessário sem preferência anterior');
assert.equal(w.fbq,undefined,'Não iniciar Meta Pixel antes do consentimento');
assert.equal(d.querySelector('script[src*="fbevents.js"]'),null);
assert.equal(w.XTLMeta.track('AddToCart',{value:27}),false,'Não emitir eventos sem consentimento');
d.getElementById('analyticsReject').click();
assert.equal(w.localStorage.getItem('disk-panquecao-analytics-consent-v1'),'rejected');
assert.equal(w.fbq,undefined,'Rejeição não pode carregar Pixel');
assert.equal(w.XTLMeta.track('Lead'),false);
d.getElementById('analyticsManage').click();
assert.equal(notice.hidden,false,'Preferência deve ser editável');
d.getElementById('analyticsAccept').click();
assert.equal(w.localStorage.getItem('disk-panquecao-analytics-consent-v1'),'accepted');
assert.equal(typeof w.fbq,'function','Pixel precisa iniciar com consentimento');
assert.equal(d.querySelectorAll('script[src*="fbevents.js"]').length,1,'Carregar SDK uma vez');
const calls=()=>[...(w.fbq.queue||[])].filter(args=>args[0]==='track');
assert.equal(calls().filter(args=>args[1]==='PageView').length,1);
assert.equal(calls().filter(args=>args[1]==='ViewContent').length,1);
assert.equal(calls().find(args=>args[1]==='ViewContent')[2].content_category,'acai');
assert.equal(w.XTLMeta.track('AddToCart',{currency:'BRL',value:27}),true);
assert.equal(calls().filter(args=>args[1]==='AddToCart').length,1);
assert.equal(w.XTLMeta.track('Purchase',{value:27}),false,
    'Purchase não representa pré-registro de pedido');
assert.equal(calls().filter(args=>args[1]==='Purchase').length,0);
d.getElementById('analyticsManage').click();
d.getElementById('analyticsReject').click();
assert.equal(w.XTLMeta.track('AddToCart',{value:50}),false,'Respeitar revogação');
assert.equal(calls().filter(args=>args[1]==='AddToCart').length,1);
assert.equal(calls().filter(args=>args[1]==='PageView').length,1,'Não disparar PageView duplicado');
console.log('PASS META PIXEL: opt-in, 12 categorias compatíveis, rejeição, aceitação, revogação, eventos corretos e Purchase bloqueado sem venda.');
