'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {JSDOM}=require('jsdom');
const html=fs.readFileSync('demo-fluxo.html','utf8');
const dom=new JSDOM(html,{url:'https://preview.example.test/demo-fluxo.html',runScripts:'outside-only'});
const w=dom.window,d=w.document;
const script=[...d.querySelectorAll('script')].find(el=>el.textContent.includes('function createWhatsAppMessage'));
assert.ok(script,'Demo JS must exist');
w.setTimeout=()=>1;
w.clearTimeout=()=>{};
w.eval(script.textContent);
const id=name=>d.getElementById(name);
const click=name=>id(name).click();
assert.equal(id('closedDialog').hasAttribute('open'),true);
assert.equal(id('clientStoreStatus').textContent.includes('fechada'),true);
assert.equal(id('sendDemoOrder').getAttribute('type'),'button');
assert.equal(id('openCheckout').hidden,true);
click('subscribeFromDialog');
assert.match(id('subscriptionStatus').textContent,/SOMENTE nesta página/);
click('openStore');
assert.equal(id('openCheckout').hidden,false);
assert.equal(id('closedDialog').hasAttribute('open'),false);
assert.match(id('toast').textContent,/NOTIFICAÇÃO SIMULADA/);
click('sendDemoOrder');
assert.match(id('clientOrderStatus').textContent,/Aguardando aprovação/);
assert.equal(id('reviewButtons').hidden,false);
click('rejectOrder');
assert.equal(id('rejectionForm').hidden,false);
click('confirmReject');
assert.match(id('reasonError').textContent,/motivo/);
id('rejectionReason').value='Produto indisponível';
click('confirmReject');
assert.match(id('clientOrderStatus').textContent,/REJEITADO/);
assert.match(id('clientOrderDetail').textContent,/Produto indisponível/);
assert.equal(id('reviewButtons').hidden,true);
click('approveOrder'); // A rejected order cannot be approved.
assert.match(id('clientOrderStatus').textContent,/REJEITADO/);
click('restartDemo');
click('openStore');
id('customerPhone').value='51987654321';
click('sendDemoOrder');
click('approveOrder');
assert.match(id('clientOrderStatus').textContent,/APROVADO/);
assert.equal(id('reviewButtons').hidden,true);
assert.equal(id('approvedWhatsApp').hidden,false);
assert.match(id('whatsAppDraft').textContent,/Seu pré-pedido DEMO-002 foi aprovado/);
assert.equal(id('openWhatsApp').disabled,true,'No automatic external WhatsApp');
id('confirmPhone').checked=true;
id('confirmPhone').dispatchEvent(new w.Event('change',{bubbles:true}));
assert.equal(id('openWhatsApp').disabled,false);
click('closeStore');
assert.equal(id('clientStoreStatus').textContent.includes('fechada'),true);
assert.equal(id('openCheckout').hidden,true);
assert.match(html,/DEMONSTRAÇÃO — NÃO ENVIA PEDIDOS/);
assert.doesNotMatch(html,/fetch\(['"]\/api\/order/);
assert.doesNotMatch(html,/fetch\(['"]\/api\/telegram/);
console.log('PASS XTL Food complete demo: close/open, opt-in simulation, pending/rejection with reason, approval, WhatsApp consent and no real requests');
